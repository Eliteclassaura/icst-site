#!/usr/bin/env node
/**
 * Fork only: bake a client's manifest into the app as a TypeScript constant (`apps/h2o/src/client/baked.ts`), so the build needs no
 * file read and CLIENT_MANIFEST_JSON is optional. `--check` fails when the committed constant is stale.
 *   node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON tools/client-kit/bin/bake.ts <slug> [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadManifest } from '../src/load.ts'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const [slug, flag] = process.argv.slice(2)
if (!slug) {
  process.stderr.write('usage: bake <slug> [--check]\n')
  process.exit(2)
}
const manifest = loadManifest(path.join(repo, 'clients', slug))
const out = path.join(repo, 'apps/h2o/src/client/baked.ts')
const nsOut = path.join(repo, 'apps/h2o/src/client/storage-namespace.ts')
// Browser-safe constant (no manifest in the client bundle): the prefix of every browser-storage key this build uses.
const nsText = `/** GENERATED by tools/client-kit/bin/bake.ts from clients/${slug}/manifest.json (client.tenantKey). Do not edit. */\nexport const STORAGE_NAMESPACE = ${JSON.stringify(manifest.client.tenantKey.toLowerCase())}\n`
const text = `import type { Manifest } from './manifest'

/** GENERATED by tools/client-kit/bin/bake.ts from clients/${slug}/manifest.json. Do not edit: change the manifest and re-bake. */
export const BAKED_SLUG = ${JSON.stringify(slug)}
export const BAKED_MANIFEST: Manifest = ${JSON.stringify(manifest, null, 2)}
`
if (flag === '--check') {
  let have = ''
  try {
    have = readFileSync(out, 'utf8')
  } catch {
    /* missing */
  }
  let haveNs = ''
  try {
    haveNs = readFileSync(nsOut, 'utf8')
  } catch {
    /* missing */
  }
  if (have !== text || haveNs !== nsText) {
    process.stderr.write('apps/h2o/src/client/baked.ts or storage-namespace.ts is out of date; run bake\n')
    process.exit(1)
  }
  process.stdout.write('ok: baked.ts is current\n')
} else {
  writeFileSync(out, text)
  writeFileSync(nsOut, nsText)
  process.stdout.write(`baked clients/${slug}/manifest.json into apps/h2o/src/client/baked.ts\n`)
}
