/**
 * Deterministic emitters. Same contract in → byte-identical output out.
 * No Date.now(), no random, keys always sorted where order is not semantic.
 */
import type { DesignContract } from '../schema.ts'
import { contrastRatio, REQUIRED, type ContrastResult } from '../contrast.ts'

const HEADER = '/* Generated by @factory/design-contract — do not edit. Source: design-contract.json */\n'

const sortedEntries = <T>(o: Record<string, T>) => Object.entries(o).sort(([a], [b]) => a.localeCompare(b))

/** tokens.css — legacy custom properties verbatim + semantic role aliases. */
export function emitCss(c: DesignContract): string {
  const lines: string[] = [HEADER, ':root {']
  lines.push('  /* Legacy custom properties — preserved verbatim for parity */')
  for (const [name, t] of sortedEntries(c.legacyVars)) lines.push(`  ${name}: ${t.value};`)
  lines.push('', '  /* Semantic colour roles */')
  for (const [role, t] of sortedEntries(c.colors)) lines.push(`  --color-${kebab(role)}: ${t.value};`)
  lines.push('', '  /* Typography */')
  lines.push(
    `  --font-display: "${c.typography.display.family}", ${c.typography.display.fallbacks.join(', ')};`,
  )
  lines.push(`  --font-text: "${c.typography.text.family}", ${c.typography.text.fallbacks.join(', ')};`)
  for (const [k, t] of sortedEntries(c.typography.scale)) lines.push(`  --fs-${k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.typography.weights)) lines.push(`  --w-${k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.typography.lineHeights)) lines.push(`  --lh-${k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.typography.letterSpacing)) lines.push(`  --ls-${k}: ${t.value};`)
  lines.push(`  --measure-min: ${c.typography.measure.value.min}ch;`)
  lines.push(`  --measure: ${c.typography.measure.value.ideal}ch;`)
  lines.push(`  --measure-max: ${c.typography.measure.value.max}ch;`)
  lines.push('', '  /* Layout */')
  for (const [k, t] of sortedEntries(c.layout.spacing)) lines.push(`  --s-${k}: ${t.value};`)
  lines.push(`  --maxw: ${c.layout.containerMax.value};`)
  lines.push(`  --nav-h: ${c.layout.navHeight.value};`)
  for (const [k, t] of sortedEntries(c.layout.radii))
    lines.push(`  --radius${k === 'base' ? '' : '-' + k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.layout.borders)) lines.push(`  --border-${k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.layout.shadows)) lines.push(`  --shadow-${k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.layout.zIndex)) lines.push(`  --z-${k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.layout.breakpoints)) lines.push(`  --bp-${kebab(k)}: ${t.value}px;`)
  lines.push('', '  /* Motion & focus */')
  for (const [k, t] of sortedEntries(c.motion.durations))
    lines.push(`  --dur${k === 'base' ? '' : '-' + k}: ${t.value};`)
  for (const [k, t] of sortedEntries(c.motion.easings))
    lines.push(`  --ease${k === 'base' ? '' : '-' + k}: ${t.value};`)
  lines.push(`  --focus-outline: ${c.focus.outline.value};`)
  lines.push(`  --focus-offset: ${c.focus.offset.value};`)
  lines.push('', `  color-scheme: ${c.brand.colorScheme === 'both' ? 'light dark' : c.brand.colorScheme};`)
  lines.push('}', '')
  return lines.join('\n')
}

/** fonts.css — @font-face for every file, plus the optical rules as utility classes. */
export function emitFontsCss(c: DesignContract): string {
  const lines: string[] = [HEADER]
  for (const fam of [c.typography.display, c.typography.text]) {
    for (const f of fam.files) {
      lines.push('@font-face {')
      lines.push(`  font-family: "${fam.family}";`)
      lines.push(`  font-style: ${f.style};`)
      if (f.weight !== undefined) lines.push(`  font-weight: ${f.weight};`)
      lines.push(`  font-display: ${fam.display};`)
      lines.push(`  src: url("${f.path}") format("woff2")${f.axes.length ? ' tech(variations)' : ''};`)
      if (f.unicodeRange) lines.push(`  unicode-range: ${f.unicodeRange};`)
      lines.push('}')
    }
  }
  const rules = Object.entries(c.typography.display.opticalRules)
  if (rules.length) {
    lines.push('', '/* Display face optical rules (see design-contract typography.display.opticalRules) */')
    lines.push('.font-display, h1, h2, .num {')
    lines.push(`  font-family: var(--font-display);`)
    for (const [k, v] of rules) lines.push(`  ${k}: ${v};`)
    lines.push('}')
  }
  lines.push('')
  return lines.join('\n')
}

/** Preload <link> attributes for critical font files, for the app layout to render. */
export function preloadFonts(c: DesignContract): Array<{ href: string; type: string }> {
  return [c.typography.display, c.typography.text]
    .flatMap((f) => f.files)
    .filter((f) => f.preload)
    .map((f) => ({ href: f.path, type: 'font/woff2' }))
}

/** tokens.ts — typed constants for code that needs values (charts, meta theme-color, e-mail). */
export function emitTs(c: DesignContract): string {
  const colors = Object.fromEntries(sortedEntries(c.colors).map(([k, t]) => [k, t.value]))
  const palette = Object.fromEntries(sortedEntries(c.palette).map(([k, t]) => [k, t.value]))
  const spacing = Object.fromEntries(sortedEntries(c.layout.spacing).map(([k, t]) => [k, t.value]))
  const breakpoints = Object.fromEntries(sortedEntries(c.layout.breakpoints).map(([k, t]) => [k, t.value]))
  const scale = Object.fromEntries(sortedEntries(c.typography.scale).map(([k, t]) => [k, t.value]))
  return [
    '// Generated by @factory/design-contract — do not edit. Source: design-contract.json',
    `export const colors = ${JSON.stringify(colors, null, 2)} as const`,
    `export const palette = ${JSON.stringify(palette, null, 2)} as const`,
    `export const spacing = ${JSON.stringify(spacing, null, 2)} as const`,
    `export const breakpoints = ${JSON.stringify(breakpoints, null, 2)} as const`,
    `export const typeScale = ${JSON.stringify(scale, null, 2)} as const`,
    `export const fonts = { display: ${JSON.stringify(c.typography.display.family)}, text: ${JSON.stringify(c.typography.text.family)} } as const`,
    `export const themeColor = ${JSON.stringify(c.colors.canvas.value)}`,
    '',
  ].join('\n')
}

/** contrast-report.json — every declared pair with ratio, requirement and pass/fail. */
export function contrastReport(c: DesignContract): { pass: boolean; results: ContrastResult[] } {
  const results = c.accessibility.contrastPairs.map((p) => {
    const fg = (c.colors as Record<string, { value: string }>)[p.foreground]?.value
    const bg = (c.colors as Record<string, { value: string }>)[p.background]?.value
    if (!fg || !bg) throw new Error(`contrast pair references unknown role: ${p.foreground}/${p.background}`)
    const ratio = Math.round(contrastRatio(fg, bg) * 100) / 100
    const required = REQUIRED[p.use] ?? 4.5
    return {
      foreground: p.foreground,
      background: p.background,
      use: p.use,
      fg,
      bg,
      ratio,
      required,
      pass: ratio >= required,
    }
  })
  return { pass: results.every((r) => r.pass), results }
}

function kebab(s: string): string {
  return s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
}
